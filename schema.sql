  CREATE TABLE IF NOT EXISTS mun_members (
    id TEXT PRIMARY KEY, email TEXT NOT NULL, name TEXT NOT NULL, committee TEXT NOT NULL DEFAULT '',
    position TEXT NOT NULL DEFAULT '', photo TEXT NOT NULL DEFAULT '', role TEXT NOT NULL DEFAULT 'Member',
    active INTEGER NOT NULL DEFAULT 1
  );
  CREATE TABLE IF NOT EXISTS mun_sessions (id TEXT PRIMARY KEY, member TEXT NOT NULL REFERENCES mun_members(id), expires BIGINT NOT NULL);
  CREATE TABLE IF NOT EXISTS mun_oauth_attempts (
    id TEXT PRIMARY KEY, verifier TEXT NOT NULL, nonce TEXT NOT NULL, expires BIGINT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS mun_posts (
    id TEXT PRIMARY KEY, type TEXT NOT NULL, title TEXT NOT NULL, body TEXT NOT NULL,
    options TEXT NOT NULL, pinned INTEGER NOT NULL DEFAULT 0, created BIGINT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS mun_votes (
    post TEXT NOT NULL REFERENCES mun_posts(id) ON DELETE CASCADE, member TEXT NOT NULL REFERENCES mun_members(id),
    choice INTEGER NOT NULL, PRIMARY KEY(post, member)
  );
  CREATE TABLE IF NOT EXISTS mun_transactions (
    id TEXT PRIMARY KEY, member TEXT NOT NULL REFERENCES mun_members(id), amount INTEGER NOT NULL,
    reason TEXT NOT NULL, date TEXT NOT NULL, by TEXT NOT NULL,
    sequence BIGINT GENERATED ALWAYS AS IDENTITY
  );
  CREATE TABLE IF NOT EXISTS mun_quizzes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, question TEXT NOT NULL UNIQUE, options TEXT NOT NULL,
    answer INTEGER NOT NULL, explanation TEXT NOT NULL, starts TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS mun_answers (
    member TEXT NOT NULL REFERENCES mun_members(id), day TEXT NOT NULL, correct INTEGER NOT NULL,
    answer TEXT NOT NULL, explanation TEXT NOT NULL, PRIMARY KEY(member, day)
  );
  CREATE TABLE IF NOT EXISTS mun_resources (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT NOT NULL UNIQUE, category TEXT NOT NULL, body TEXT NOT NULL, url TEXT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS mun_transactions_member_date ON mun_transactions(member, date);
  CREATE INDEX IF NOT EXISTS mun_sessions_expiry ON mun_sessions(expires);
